fn bar(close_ms: u64, buy_usd: f64, sell_usd: f64) -> Bar {
    Bar {
        open_ms: close_ms,
        close_ms,
        n: 1,
        buy_usd,
        sell_usd,
        vwap: 100.0,
        last_px: 100.0,
    }
}

fn trade(t_entry_ms: u64, t_exit_ms: u64, side: i8, pnl_usd: f64) -> ExecutedTrade {
    ExecutedTrade {
        symbol: "xyz_NVDA".into(),
        side,
        score: 0.9,
        decile: 10,
        t_entry_ms,
        entry_px: 100.0,
        entry_last_px: 100.0,
        t_exit_ms,
        t_exit_real_ms: t_exit_ms,
        exit_px: 100.0,
        fee_entry_usd: -0.0015,
        fee_exit_usd: -0.0015,
        pnl_usd,
    }
}

#[test]
fn ewma_score_bits_reproduce_nvda_golden_row_720() {
    let bars: Vec<Bar> = NVDA_GOLDEN_ROW_720_BARS
        .iter()
        .map(|&(close_ms, buy, sell)| bar(close_ms, buy, sell))
        .collect();
    let scores = ewma_imbalance(&bars, TAU_SECS);
    let last = scores.last().unwrap();
    assert_eq!(last.close_ms, NVDA_GOLDEN_ROW_720_ENTRY_MS);
    assert_eq!(
        last.score.to_bits(),
        NVDA_GOLDEN_ROW_720_SCORE_BITS,
        "score {:?}",
        last.score
    );
}

#[test]
fn ewma_score_bits_after_one_decay_step_are_fixed() {
    for (gap_ms, want) in OPPOSING_PAIR_GAP_SCORE_BITS {
        let bars = [bar(0, 1.0, 0.0), bar(gap_ms, 0.0, 1.0)];
        let got = ewma_imbalance(&bars, TAU_SECS)[1].score;
        assert_eq!(got.to_bits(), want, "gap {gap_ms} ms score {got:?}");
    }
}

#[test]
fn stats_dispersion_bits_are_fixed() {
    let trades = [
        trade(0, 900_000, 1, 2.375),
        trade(60_000, 960_000, -1, -1.0625),
        trade(120_000, 1_020_000, 1, 0.1),
        trade(180_000, 1_080_000, -1, -3.3),
        trade(240_000, 1_140_000, 1, 4.7),
        trade(300_000, 1_200_000, -1, 0.333),
    ];
    let refs: Vec<&ExecutedTrade> = trades.iter().collect();
    let b = block(&refs).unwrap();
    assert_eq!(
        b.t_stat.to_bits(),
        0x3fddb9ab3831a867,
        "t_stat {:?}",
        b.t_stat
    );
    assert_eq!(
        b.sharpe.to_bits(),
        0x3fc84544c190f45f,
        "sharpe {:?}",
        b.sharpe
    );
    assert_eq!(
        b.sortino.to_bits(),
        0x3fd7b4c82a5ba2ae,
        "sortino {:?}",
        b.sortino
    );
}
